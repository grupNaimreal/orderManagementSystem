using Microsoft.AspNetCore.HttpOverrides;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;
using Npgsql;
using orderManagementSystem.Data;
using orderManagementSystem.Services;

AppContext.SetSwitch("Npgsql.EnableLegacyTimestampBehavior", true);

var builder = WebApplication.CreateBuilder(args);

var rawConnectionString = builder.Configuration.GetConnectionString("DefaultConnection")
    ?? throw new InvalidOperationException("Connection string 'DefaultConnection' not found.");

var connectionString = NormalizePostgresConnectionString(rawConnectionString);

builder.Services.AddDbContext<ApplicationDbContext>(options =>
    options.UseNpgsql(connectionString));

builder.Services.AddDatabaseDeveloperPageExceptionFilter();

builder.Services.AddDefaultIdentity<IdentityUser>(options =>
{
    options.SignIn.RequireConfirmedAccount = false;
})
.AddRoles<IdentityRole>()
.AddEntityFrameworkStores<ApplicationDbContext>();

builder.Services.AddDistributedMemoryCache();
builder.Services.AddSession(options =>
{
    options.IdleTimeout = TimeSpan.FromMinutes(10);
    options.Cookie.HttpOnly = true;
    options.Cookie.IsEssential = true;
    options.Cookie.SameSite = SameSiteMode.Lax;
});

builder.Services.Configure<ForwardedHeadersOptions>(options =>
{
    options.ForwardedHeaders = ForwardedHeaders.XForwardedFor | ForwardedHeaders.XForwardedProto;
    options.KnownIPNetworks.Clear();
    options.KnownProxies.Clear();
});

builder.Services.AddHttpContextAccessor();
builder.Services.AddScoped<CustomerSessionService>();
builder.Services.AddScoped<AuditLogService>();
builder.Services.AddHttpClient<MayaCheckoutService>();
builder.Services.AddHostedService<UnpaidOrderExpiryService>();

builder.Services.AddControllersWithViews();
builder.Services.AddRazorPages();

var app = builder.Build();

app.UseForwardedHeaders();

// Hardened HTTP security headers for POS & customer sessions
app.Use(async (context, next) =>
{
    context.Response.Headers["X-Content-Type-Options"] = "nosniff";
    context.Response.Headers["X-Frame-Options"] = "SAMEORIGIN";
    context.Response.Headers["Referrer-Policy"] = "strict-origin-when-cross-origin";
    context.Response.Headers["Permissions-Policy"] = "camera=(self), microphone=(), geolocation=()";
    await next();
});

if (app.Environment.IsDevelopment())
{
    app.UseMigrationsEndPoint();
}
else
{
    app.UseExceptionHandler("/Home/Error");
    app.UseHsts();
}

app.UseHttpsRedirection();

// Cache static product photos and brand assets for 7 days to eliminate repeat image downloads
app.UseStaticFiles(new StaticFileOptions
{
    OnPrepareResponse = ctx =>
    {
        if (ctx.File.PhysicalPath != null &&
            (ctx.Context.Request.Path.StartsWithSegments("/images") ||
             ctx.Context.Request.Path.StartsWithSegments("/css") ||
             ctx.Context.Request.Path.StartsWithSegments("/js")))
        {
            ctx.Context.Response.Headers["Cache-Control"] = "public,max-age=604800";
        }
    }
});

app.UseRouting();

app.UseSession();

app.UseAuthentication();
app.UseAuthorization();

app.MapStaticAssets();

app.MapControllers();

app.MapControllerRoute(
    name: "default",
    pattern: "{controller=Home}/{action=Index}/{id?}")
    .WithStaticAssets();

app.MapRazorPages()
   .WithStaticAssets();

// Lightweight health endpoint for zero-cost uptime pingers (prevents Render free-tier sleep)
app.MapGet("/health", () => Results.Ok(new { status = "ok" }));

using (var scope = app.Services.CreateScope())
{
    var dbContext = scope.ServiceProvider.GetRequiredService<ApplicationDbContext>();
    await dbContext.Database.MigrateAsync();

    // Ensure AuditLogs table exists in PostgreSQL even if an EF migration was skipped
    await dbContext.Database.ExecuteSqlRawAsync("""
        CREATE TABLE IF NOT EXISTS "AuditLogs" (
            "Id" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
            "TimestampUtc" timestamp without time zone NOT NULL,
            "ActorName" character varying(256) NOT NULL,
            "ActorRole" character varying(50) NOT NULL,
            "ActionType" character varying(60) NOT NULL,
            "EntityName" character varying(60) NOT NULL,
            "EntityId" character varying(60) NULL,
            "Details" character varying(500) NOT NULL,
            CONSTRAINT "PK_AuditLogs" PRIMARY KEY ("Id")
        );
        """);

    await MenuSeeder.SeedAsync(dbContext);
}

await orderManagementSystem.Security.IdentitySeeder.SeedAsync(app.Services, app.Configuration);

app.Run();

static string NormalizePostgresConnectionString(string input)
{
    var trimmed = input.Trim();
    if (!trimmed.StartsWith("postgres://", StringComparison.OrdinalIgnoreCase)
        && !trimmed.StartsWith("postgresql://", StringComparison.OrdinalIgnoreCase))
    {
        return trimmed;
    }

    var uri = new Uri(trimmed);
    var userInfo = uri.UserInfo.Split(':', 2);
    var csb = new NpgsqlConnectionStringBuilder
    {
        Host = uri.Host,
        Port = uri.Port > 0 ? uri.Port : 5432,
        Database = uri.AbsolutePath.TrimStart('/'),
        Username = Uri.UnescapeDataString(userInfo[0]),
        Password = userInfo.Length > 1 ? Uri.UnescapeDataString(userInfo[1]) : string.Empty,
        SslMode = SslMode.Require
    };

    return csb.ConnectionString;
}